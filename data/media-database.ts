/**
 * 批量分类
 */
export function batchClassify(
  mediaNames: string[]
): Map<string, MediaCategory> {
  const result = new Map<string, MediaCategory>();
  for (const name of mediaNames) {
    result.set(name, classifyMedia(name));
  }
  return result;
}

/**
 * 按类别统计
 */
export function countByCategory(
  classified: Map<string, MediaCategory>
): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const [, category] of classified) {
    counts[category] = (counts[category] || 0) + 1;
  }
  return counts;
}
